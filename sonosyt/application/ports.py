"""The application's view of the outside world.

Each port is what a use case needs, phrased in its own terms. Adapters in
sonosyt/adapters implement them for Sonos (SoCo), YouTube (yt-dlp), ffmpeg,
a JSON file, LRCLIB and the local network; tests implement them with fakes.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Iterator, Protocol

from ..domain.track import Track


class SpeakerSystem(Protocol):
    """The Sonos rooms. Rooms are named as in the Sonos app; unknown names raise SpeakerError."""

    def speakers(self, refresh: bool = False) -> list[dict]: ...
    def overview(self) -> list[dict]: ...  # one entry per playing group: what plays, volume
    def address(self, speaker: str) -> str: ...
    def enqueue(self, speaker: str, items: list[tuple[Track, str]], mode: str) -> int: ...
    def control(self, speaker: str, action: str, value: int | None = None, to: int | None = None) -> None: ...
    def set_volume(self, speaker: str, volume: int, single: bool = False) -> None: ...
    def status(self, speaker: str) -> dict: ...
    def queue(self, speaker: str) -> list[dict]: ...
    def rooms(self, speaker: str) -> list[dict]: ...
    def group(self, speaker: str, room: str, join: bool) -> None: ...
    def set_eq(self, room: str, bass=None, treble=None, loudness=None) -> dict: ...
    def favorites(self, speaker: str) -> list[dict]: ...
    def play_favorite(self, speaker: str, index: int) -> str: ...
    def reachable(self, speaker: str) -> bool: ...


class VideoCatalog(Protocol):
    """YouTube: finding videos. Failures raise MediaError."""

    def lookup(self, query: str, limit: int = 10) -> list[Track]: ...
    def related(self, video_id: str) -> list[Track]: ...
    def suggest(self, query: str) -> list[str]: ...
    def thumbnail(self, video_id: str) -> bytes: ...


@dataclass
class VideoPiece:
    """Bytes ``start``..``end`` (inclusive) of a video file of ``size`` bytes (None if unknown)."""

    start: int
    end: int
    size: int | None
    content_type: str
    chunks: Iterator[bytes]


class VideoFeed(Protocol):
    """The picture of a video (no sound) for the phone, in pieces. Failures raise MediaError."""

    def warm(self, video_id: str) -> None: ...  # look it up now, so playback starts quickly
    def open(self, video_id: str, start: int, end: int | None) -> VideoPiece: ...


class ConversionJob(Protocol):
    error: str | None
    final: Path

    @property
    def ok(self) -> bool: ...
    @property
    def done(self): ...  # threading.Event
    def wait_for_data(self, timeout: float) -> bool: ...
    def follow(self) -> Iterator[bytes]: ...


class AudioConverter(Protocol):
    """Turns videos into MP3 the speakers can play, keeping finished files in a cache."""

    max_cache_bytes: int

    def ensure(self, video_id: str) -> ConversionJob: ...
    def prefetch(self, video_ids: list[str]) -> None: ...
    def cached(self, video_id: str) -> Path | None: ...
    def live(self, video_id: str) -> Iterator[bytes]: ...
    def cache_info(self) -> dict: ...
    def clear_cache(self) -> int: ...


class LibraryRepository(Protocol):
    """Favourites, history, playlists, resume positions, alarms and autoplay rooms."""

    def snapshot(self) -> dict: ...
    def tracks(self) -> list[Track]: ...
    def set_favorite(self, track: Track, on: bool) -> None: ...
    def played(self, tracks: list[Track]) -> None: ...
    def recent_ids(self) -> set[str]: ...
    def clear_history(self) -> None: ...
    def playlist_add(self, name: str, track: Track) -> None: ...
    def playlist_set(self, name: str, tracks: list[Track]) -> None: ...
    def playlist_remove(self, name: str, video_id: str) -> None: ...
    def playlist_delete(self, name: str) -> None: ...
    def position(self, video_id: str) -> int: ...
    def set_position(self, video_id: str, seconds: int) -> None: ...
    def alarms(self) -> list[dict]: ...
    def save_alarm(self, data: dict) -> dict: ...
    def delete_alarm(self, alarm_id: str) -> None: ...
    def disable_alarm(self, alarm_id: str) -> None: ...
    def presets(self) -> list[dict]: ...
    def save_preset(self, data: dict) -> dict: ...
    def delete_preset(self, preset_id: str) -> None: ...
    def autoplay(self, speaker: str) -> bool: ...
    def autoplay_speakers(self) -> list[str]: ...
    def set_autoplay(self, speaker: str, on: bool) -> None: ...


class LyricsSource(Protocol):
    """A lyrics database. Returns candidate entries; may raise on network trouble."""

    def search(self, params: dict) -> list[dict]: ...


class Thumbnails(Protocol):
    """Cover images (JPEG bytes). Raises MediaError if there is none."""

    def get(self, video_id: str) -> bytes: ...


class Network(Protocol):
    def local_address_for(self, peer: str) -> str: ...
    def youtube_reachable(self) -> bool: ...


class Tools(Protocol):
    def ytdlp_version(self) -> str: ...
